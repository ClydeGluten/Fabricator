import { test, expect } from '@playwright/test'

test('offline player card shows saved coordinates and inventory, with disabled controls', async ({ page }) => {
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/server/srv_offline/players')
  await page.getByRole('button', { name: 'View Steve: coordinates, inventory and controls' }).click()
  await expect(page.getByText('Last saved data', { exact: false })).toBeVisible()
  await expect(page.locator('.player-card__location')).toContainText('X 12.5 · Y 64 · Z -20')
  await expect(page.getByRole('button', { name: 'Heal', exact: true })).toBeDisabled()
  await page.getByRole('button', { name: 'Inventory · backpack and hotbar, 0: minecraft:diamond × 3', exact: true }).click()
  await expect(page.locator('.inventory__detail')).toContainText('minecraft:diamond × 3')
  await page.screenshot({ path: '../.artifacts/player-card-desktop.png', fullPage: true })
  expect(errors).toEqual([])
})

test('live player controls send the expected command and refresh current health', async ({ page, request }) => {
  await page.goto('/server/srv_live/players')
  await page.getByRole('button', { name: 'View Steve: coordinates, inventory and controls' }).click()
  await expect(page.getByText('Live read', { exact: false })).toBeVisible()
  await page.getByRole('button', { name: 'Heal', exact: true }).click()
  await expect(page.locator('.player-card__stats')).toContainText('20 HP')
  await page.getByLabel('X', { exact: true }).fill('123')
  await page.getByLabel('Y', { exact: true }).fill('70')
  await page.getByLabel('Z', { exact: true }).fill('-456')
  await page.getByLabel('Dimension', { exact: true }).fill('minecraft:the_nether')
  await page.getByRole('button', { name: 'Teleport', exact: true }).click()
  await expect(page.locator('.player-card__notice')).toContainText('Command sent')
  const log = await (await request.get('/test/commands')).json()
  expect(log.commands).toContain('execute in minecraft:the_nether run tp Steve 123.0 70.0 -456.0')
})

test('whitelist batch editing persists and works on a mobile viewport', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/server/srv_offline/players')
  const editor = page.getByRole('region', { name: 'Whitelist', exact: true })
  await editor.getByLabel('Add players (up to 20 names)').fill('Alex, Friend_One, alex')
  await editor.getByRole('button', { name: 'Add to whitelist', exact: true }).click()
  await expect(editor.locator('.whitelist-editor__entries li')).toHaveCount(2)
  await editor.getByText('Only whitelisted players can join', { exact: true }).click()
  await expect(editor.getByRole('switch', { name: 'Only whitelisted players can join' })).toBeChecked()
  await page.reload()
  await expect(editor.getByRole('switch', { name: 'Only whitelisted players can join' })).toBeChecked()
  await editor.getByRole('button', { name: 'Remove Alex from whitelist' }).click()
  await expect(editor.locator('.whitelist-editor__entries li')).toHaveCount(1)
  await page.screenshot({ path: '../.artifacts/whitelist-mobile.png', fullPage: true })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy()
  await page.getByRole('button', { name: 'View Steve: coordinates, inventory and controls' }).click()
  await expect(page.getByRole('button', { name: 'Heal', exact: true })).toBeDisabled()
  await page.screenshot({ path: '../.artifacts/player-card-mobile.png', fullPage: true })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy()
})

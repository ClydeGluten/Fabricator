import { test, expect } from '@playwright/test'

test('sync preview excludes client-only, keeps optional/server-only and applies exact versions', async ({ page, request }) => {
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/server/srv_offline/mods')
  const panel = page.getByRole('region', { name: 'Modrinth instance sync', exact: true })
  await panel.getByLabel('Source instance').selectOption('Browser instance')
  await panel.getByRole('button', { name: 'Preview sync', exact: true }).click()
  await expect(panel.getByText('Client-only mods skipped: 1', { exact: true })).toBeVisible()
  await expect(panel.locator('.instance-sync__changes')).toContainText('Optional mod')
  await expect(panel.locator('.instance-sync__changes')).toContainText('shared-v2.jar')
  await expect(panel.locator('.instance-sync__changes')).not.toContainText('client.jar')
  await expect(panel.getByText('Other server mods kept: 1', { exact: true })).toBeVisible()
  await page.screenshot({ path: '../.artifacts/instance-sync-desktop.png', fullPage: true })
  await panel.getByRole('button', { name: 'Apply sync', exact: true }).click()
  await expect(panel.getByRole('status')).toContainText('Sync complete')
  const result = await (await request.get('/test/mod-files/srv_offline')).json()
  expect(result.files).toEqual(['optional.jar', 'server-extra.jar', 'shared-v2.jar'])
  expect(result.sourceFiles).toEqual(['client.jar', 'optional.jar', 'shared-v2.jar'])
  await page.reload()
  await expect(panel.getByLabel('Source instance')).toHaveValue('Browser instance')
  expect(errors).toEqual([])
})

test('a newly created instance can be connected without restart on mobile', async ({ page, request }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/server/srv_offline/mods')
  const panel = page.getByRole('region', { name: 'Modrinth instance sync', exact: true })
  await expect(panel.getByLabel('Source instance')).toBeVisible()
  await request.post('/test/add-instance')
  await panel.getByRole('button', { name: 'Refresh list', exact: true }).click()
  await panel.getByLabel('Source instance').selectOption('New browser instance')
  await panel.getByRole('button', { name: 'Preview sync', exact: true }).click()
  await expect(panel.locator('.instance-sync__changes')).toContainText('second.jar')
  await page.screenshot({ path: '../.artifacts/instance-sync-mobile.png', fullPage: true })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy()
  await panel.getByRole('button', { name: 'Apply sync', exact: true }).click()
  await expect(panel.getByRole('status')).toContainText('Sync complete')
  expect((await (await request.get('/test/mod-files/srv_offline')).json()).files).toEqual(['second.jar', 'server-extra.jar'])
  await page.reload()
  await expect(panel.getByLabel('Source instance')).toHaveValue('New browser instance')
})

test('running server can preview but cannot apply', async ({ page }) => {
  await page.goto('/server/srv_live/mods')
  const panel = page.getByRole('region', { name: 'Modrinth instance sync', exact: true })
  await panel.getByLabel('Source instance').selectOption('Browser instance')
  await panel.getByRole('button', { name: 'Preview sync', exact: true }).click()
  await expect(panel.getByText('Stop the Minecraft server before applying this preview.', { exact: true })).toBeVisible()
  await expect(panel.getByRole('button', { name: 'Apply sync', exact: true })).toBeDisabled()
})
